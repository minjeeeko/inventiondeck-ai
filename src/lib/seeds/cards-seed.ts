import { Card, CardCategory } from "@/types";

function makeCards(category: CardCategory, items: { title: string; description: string; tags: string[] }[]): Card[] {
  return items.map((item, i) => ({
    id: `${category}-${String(i + 1).padStart(3, "0")}`,
    category,
    title: item.title,
    description: item.description,
    tags: item.tags,
    popularity: Math.floor(Math.random() * 100),
    synced_at: new Date().toISOString(),
  }));
}

